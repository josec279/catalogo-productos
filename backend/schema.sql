create table if not exists products (
  id bigint generated by default as identity primary key,
  name text not null,
  price numeric not null,
  stock integer default 0,
  image_url text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 1. Habilitar la seguridad a nivel de filas
alter table products enable row level security;

-- 2. Permitir que cualquier usuario (autenticado o no) pueda ver los productos
drop policy if exists "Cualquiera puede ver los productos" on products;
create policy "Cualquiera puede ver los productos" on products for select to public using (true);
